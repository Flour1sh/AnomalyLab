def bind_event(g, previous, previous_pin, target, target_pin, dispatcher, handler, x):
    binding = create(g, "默认|BindEventto"+dispatcher, x, -600)
    event = create(g, "事件分发器|创建事件", x, -300)
    connect(previous, previous_pin, binding, "execute")
    connect(target, target_pin, binding, "self")
    connect(event, "OutputDelegate", binding, "Delegate")
    return binding, event

def run():
    g = graph(CHAR, "EventGraph")
    before = nodes(g)
    # Do not replace a user-owned or already completed BeginPlay chain.
    assert not any("BeginPlay" in n["type_id"] for n in infos(before))
    begin = execute_tool(BP+"add_event", json.dumps({"blueprint": CHAR, "event_name": "ReceiveBeginPlay", "position": {"x": -2200, "y": -600}}))["returnValue"]
    widget = create(g, "用户界面|创建控件", -1950, -600)
    value(widget, "Class", "/Game/UI/WBP_PrototypeHUD.WBP_PrototypeHUD_C")
    controller = create(g, "游戏|GetPlayerController", -2200, -250)
    connect(controller, "ReturnValue", widget, "OwningPlayer")
    connect(begin, "then", widget, "execute")
    valid = create(g, "工具集|IsValid", -1750, -250)
    connect(widget, "ReturnValue", valid, "Object")
    branch = create(g, "工具|流程控制|分支", -1650, -600)
    connect(widget, "then", branch, "execute")
    connect(valid, "ReturnValue", branch, "Condition")
    error = create(g, "开发|PrintString", -1400, -900)
    value(error, "InString", "[HUD] ERROR WBP_PrototypeHUD creation failed; gameplay remains available")
    value(error, "bPrintToScreen", "false")
    connect(branch, "else", error, "execute")
    cache = create(g, "变量|默认|设置PrototypeHUD", -1350, -600)
    connect(branch, "then", cache, "execute")
    connect(widget, "ReturnValue", cache, "PrototypeHUD")
    viewport = create(g, "用户界面|视口|AddtoViewport", -1050, -600)
    connect(cache, "then", viewport, "execute")
    connect(widget, "ReturnValue", viewport, "self")
    wallet = create(g, "变量|默认|获取BPCWallet", -1050, -250)
    get_money = create(g, "类|BPCWallet|GetMoney", -800, -600)
    connect(wallet, "BPC_Wallet", get_money, "self")
    connect(viewport, "then", get_money, "execute")
    update = create(g, "类|WBPPrototypeHUD|UpdateMoney", -500, -600)
    connect(get_money, "then", update, "execute")
    connect(get_money, "MoneyValue", update, "NewMoney")
    connect(widget, "ReturnValue", update, "self")
    money_bind, money_event = bind_event(g, update, "then", wallet, "BPC_Wallet", "OnMoneyChanged", "HandleMoneyChanged_6", -150)
    interaction = create(g, "变量|默认|获取BPCInteraction", 150, -100)
    focus_bind, focus_event = bind_event(g, money_bind, "then", interaction, "BPC_Interaction", "OnFocusedActorChanged", "HandleFocusChanged_6", 200)
    box = create(g, "Actor|GetActorOfClass", 500, -600)
    value(box, "ActorClass", "/Game/Anomalies/Containers/BP_AnomalyBox.BP_AnomalyBox_C")
    connect(focus_bind, "then", box, "execute")
    box_valid = create(g, "工具集|IsValid", 800, -200)
    connect(box, "ReturnValue", box_valid, "Object")
    box_branch = create(g, "工具|流程控制|分支", 850, -600)
    connect(box, "then", box_branch, "execute")
    connect(box_valid, "ReturnValue", box_branch, "Condition")
    outcome_bind, outcome_event = bind_event(g, box_branch, "then", box, "ReturnValue", "OnOutcomeResolved", "HandleOutcomeResolved", 1200)
    missing = create(g, "开发|PrintString", 1200, -900)
    value(missing, "InString", "[HUD] WARNING No prototype box found for outcome display")
    value(missing, "bPrintToScreen", "false")
    connect(box_branch, "else", missing, "execute")
    bound = []
    for event, name in ((money_event, "HandleMoneyChanged_6"), (focus_event, "HandleFocusChanged_6"), (outcome_event, "HandleOutcomeResolved")):
        execute_tool(BP+"set_create_event_function", json.dumps({"node": event, "function_name": name}))
        selected = execute_tool(BP+"get_create_event_function", json.dumps({"node": event}))["returnValue"]
        assert selected == name, (name, selected)
        bound.append(selected)
    compile_bp(CHAR)
    for event, name in ((money_event, "HandleMoneyChanged_6"), (focus_event, "HandleFocusChanged_6"), (outcome_event, "HandleOutcomeResolved")):
        assert execute_tool(BP+"get_create_event_function", json.dumps({"node": event}))["returnValue"] == name
    save([CHAR])
    return {"ok": True, "bound_callbacks": bound, "preserved_existing_event_nodes": len(before), "new_event_nodes": len(nodes(g))-len(before), "compile": "PASS", "saved": True}
